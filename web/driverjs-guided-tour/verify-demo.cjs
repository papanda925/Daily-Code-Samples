'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '../..');
const html = fs.readFileSync(path.join(root, 'docs/demos/driverjs-guided-tour/index.html'), 'utf8');
const daily = fs.readFileSync(path.join(root, 'docs/demos/browser-library-labs/daily.js'), 'utf8');
const sm = html.match(/<script id="settings" type="application\/json">([\s\S]*?)<\/script>/);
assert.ok(sm, 'settings exist');
const settings = JSON.parse(sm[1]);
assert.equal(settings.id, 35);
assert.equal(settings.input, '記録');
assert.match(html, /id="live"/);
assert.match(html, /案内の題材/);
assert.match(html, /案内を開く/);
assert.match(daily, /driver\.js@1\.3\.6/);
const a = daily.indexOf('\n35:');
const b = daily.indexOf('\n36:', a);
assert.ok(a >= 0 && b > a, 'demo 35 is registered');
const fn = daily.slice(a + 4, b).trim().replace(/,$/, '');
assert.match(fn, /String\(v\?\?''\)/);
assert.match(fn, /title:label\+'を検索'/);
assert.match(fn, /title:label\+'を保存'/);
assert.match(fn, /d\.drive\(\)/);
assert.match(fn, /cleanup=\(\)=>d\.destroy\(\)/);
assert.doesNotThrow(() => new Function('return (' + fn + ')'));
console.log('PASS: HTML/settings, input, steps, API wiring, cleanup, syntax');
